"""Ports implemented by ERP adapters and metadata storage, never inferred from vectors."""
from typing import Any, Protocol

from .models import DiscoveryRequest

Document = dict[str, Any]


class DiscoveryAdapter(Protocol):
    # Stable ERP + tenant/index scope from trusted server configuration, never model input.
    namespace: str

    def compile_catalog(self) -> list[Document]: ...
    def authorize(self, documents: list[Document], principal: Any) -> list[Document]: ...
    def redact_question(self, question: str, principal: Any) -> str: ...
    def audit_actor(self, principal: Any) -> str: ...
    def validate_query(self, query: dict, principal: Any) -> dict: ...
    async def execute_metric(self, document: Document, request: DiscoveryRequest, principal: Any) -> dict: ...


class VectorStore(Protocol):
    namespace: str
    async def initialize(self) -> None: ...
    async def publish(self, revision: str, model: str, dimensions: int,
                      documents: list[Document], vectors: list[list[float]]) -> None: ...
    async def vector_search(self, documents: list[Document], vector: list[float],
                            model: str, dimensions: int, limit: int) -> tuple[list[str], str]: ...
    async def index_status(self) -> dict | None: ...


class Embedder(Protocol):
    async def embed(self, texts: list[str]) -> list[list[float]]: ...


class Reranker(Protocol):
    async def rerank(self, question: str, texts: list[str]) -> list[int]: ...
